"""Server-enforced authentication and patient-record authorization (localhost prototype).

- Accounts live in the existing SQLite event store. Passwords are random per account (generated by
  `python -m app.auth provision`), stored as PBKDF2-SHA256 hashes; there is no shared or hardcoded password.
- Sessions: random 256-bit token in an HttpOnly, SameSite=Strict cookie; only its SHA-256 is stored.
- Access is deny-by-default and enforced in an ASGI middleware for HTTP *and* WebSocket requests:
    * public: health/status/meta and the auth endpoints (no patient data);
    * doctor: every API route;
    * patient: GET of their own profile and monitor (HTTP and WebSocket) only;
    * the in-process simulator may POST observations with a per-process internal token.
"""

from __future__ import annotations

import argparse
import asyncio
import hashlib
import hmac
import json
import os
import re
import secrets
import time
from datetime import datetime, timezone
from http.cookies import SimpleCookie
from pathlib import Path

from starlette.responses import JSONResponse

from .db import connect

SESSION_COOKIE = "ad_session"
SESSION_SECONDS = 12 * 3600
PBKDF2_ITERATIONS = 210_000
INTERNAL_HEADER = "x-arogya-internal"

SCHEMA = """
CREATE TABLE IF NOT EXISTS auth_users (
    username      TEXT PRIMARY KEY,
    role          TEXT NOT NULL CHECK (role IN ('doctor', 'patient')),
    patient_id    TEXT,
    display_name  TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    created_at    TEXT NOT NULL,
    CHECK ((role = 'patient') = (patient_id IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS auth_users_patient ON auth_users(patient_id) WHERE patient_id IS NOT NULL;
CREATE TABLE IF NOT EXISTS auth_sessions (
    token_hash TEXT PRIMARY KEY,
    username   TEXT NOT NULL,
    created_at TEXT NOT NULL,
    expires_at REAL NOT NULL
);
"""

PUBLIC_PATHS = {"/health", "/api/v1/meta", "/api/v1/status", "/api/auth/login", "/api/auth/logout", "/api/auth/me", "/ws/heartbeat"}
# Routes a patient may use, only for their own patient id, read-only.
PATIENT_OWN = [
    re.compile(r"^/api/patients/(?P<pid>[A-Za-z0-9\-.]{1,64})/profile$"),
    re.compile(r"^/api/demo/monitor/(?P<pid>[A-Za-z0-9\-.]{1,64})$"),
    re.compile(r"^/ws/monitor/(?P<pid>[A-Za-z0-9\-.]{1,64})$"),
]


def init(db_path: str) -> None:
    with connect(db_path) as c:
        c.executescript(SCHEMA)


def hash_password(password: str, salt: bytes | None = None) -> str:
    salt = salt or secrets.token_bytes(16)
    dk = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, PBKDF2_ITERATIONS)
    return f"pbkdf2_sha256${PBKDF2_ITERATIONS}${salt.hex()}${dk.hex()}"


def verify_password(password: str, stored: str) -> bool:
    try:
        algo, iters, salt, digest = stored.split("$")
        dk = hashlib.pbkdf2_hmac("sha256", password.encode(), bytes.fromhex(salt), int(iters))
        return algo == "pbkdf2_sha256" and hmac.compare_digest(dk.hex(), digest)
    except (ValueError, TypeError):
        return False


_DUMMY_HASH = hash_password(secrets.token_urlsafe(16))


def _public(row) -> dict:
    return {"username": row["username"], "role": row["role"], "patientId": row["patient_id"], "displayName": row["display_name"]}


def upsert_user(db_path: str, username: str, role: str, display_name: str, password: str, patient_id: str | None = None) -> None:
    with connect(db_path) as c:
        c.execute(
            "INSERT INTO auth_users(username, role, patient_id, display_name, password_hash, created_at) VALUES (?,?,?,?,?,?) "
            "ON CONFLICT(username) DO UPDATE SET role=excluded.role, patient_id=excluded.patient_id, "
            "display_name=excluded.display_name, password_hash=excluded.password_hash",
            (username, role, patient_id, display_name, hash_password(password), datetime.now(timezone.utc).isoformat()),
        )
        c.execute("DELETE FROM auth_sessions WHERE username = ?", (username,))   # a new password ends old sessions


def user_for_patient(db_path: str, patient_id: str) -> dict | None:
    with connect(db_path) as c:
        row = c.execute("SELECT * FROM auth_users WHERE patient_id = ?", (patient_id,)).fetchone()
    return _public(row) if row else None


def usernames(db_path: str) -> set[str]:
    with connect(db_path) as c:
        return {r[0] for r in c.execute("SELECT username FROM auth_users")}


def user_exists(db_path: str, username: str) -> bool:
    with connect(db_path) as c:
        return c.execute("SELECT 1 FROM auth_users WHERE username = ?", (username,)).fetchone() is not None


def authenticate(db_path: str, username: str, password: str) -> dict | None:
    with connect(db_path) as c:
        row = c.execute("SELECT * FROM auth_users WHERE username = ?", (username.strip().lower(),)).fetchone()
    if row is None:
        verify_password(password, _DUMMY_HASH)   # similar timing for unknown users
        return None
    return _public(row) if verify_password(password, row["password_hash"]) else None


def _token_hash(token: str) -> str:
    return hashlib.sha256(token.encode()).hexdigest()


def create_session(db_path: str, username: str) -> str:
    token = secrets.token_urlsafe(32)
    now = time.time()
    with connect(db_path) as c:
        c.execute("DELETE FROM auth_sessions WHERE expires_at < ?", (now,))
        c.execute("INSERT INTO auth_sessions(token_hash, username, created_at, expires_at) VALUES (?,?,?,?)",
                  (_token_hash(token), username, datetime.now(timezone.utc).isoformat(), now + SESSION_SECONDS))
    return token


def session_user(db_path: str, token: str | None) -> dict | None:
    if not token or len(token) > 200:
        return None
    with connect(db_path) as c:
        row = c.execute(
            "SELECT u.* FROM auth_sessions s JOIN auth_users u ON u.username = s.username "
            "WHERE s.token_hash = ? AND s.expires_at > ?", (_token_hash(token), time.time())).fetchone()
    return _public(row) if row else None


def delete_session(db_path: str, token: str | None) -> None:
    if token:
        with connect(db_path) as c:
            c.execute("DELETE FROM auth_sessions WHERE token_hash = ?", (_token_hash(token),))


def decide(path: str, method: str, user: dict | None, internal: bool) -> tuple[bool, int, str]:
    """(allowed, status if denied, reason). Deny by default."""
    if method == "OPTIONS" or path in PUBLIC_PATHS or not (path.startswith("/api/") or path.startswith("/ws/")):
        return True, 200, ""
    if internal and method == "POST" and path == "/api/fhir/Observation":
        return True, 200, ""
    if user is None:
        return False, 401, "Sign in required."
    if user["role"] == "doctor":
        return True, 200, ""
    if user["role"] == "patient" and method in ("GET", "WEBSOCKET"):
        for rx in PATIENT_OWN:
            m = rx.match(path)
            if m and user.get("patientId") and m["pid"] == user["patientId"]:
                return True, 200, ""
    return False, 403, "This account may not access this resource."


def _cookie(headers: list[tuple[bytes, bytes]]) -> str | None:
    for k, v in headers:
        if k == b"cookie":
            try:
                c = SimpleCookie()
                c.load(v.decode("latin-1"))
                if SESSION_COOKIE in c:
                    return c[SESSION_COOKIE].value
            except Exception:
                return None
    return None


class AuthMiddleware:
    """Pure ASGI middleware so the same rules apply to HTTP requests and WebSocket handshakes."""

    def __init__(self, app, db_path: str, internal_token: str, enabled: bool = True):
        self.app, self.db_path, self.internal_token, self.enabled = app, db_path, internal_token, enabled

    async def __call__(self, scope, receive, send):
        if scope["type"] not in ("http", "websocket") or not self.enabled:
            return await self.app(scope, receive, send)
        headers = scope.get("headers") or []
        user = session_user(self.db_path, _cookie(headers))
        supplied = next((v.decode("latin-1") for k, v in headers if k == INTERNAL_HEADER.encode()), "")
        internal = bool(supplied) and hmac.compare_digest(supplied, self.internal_token)
        method = scope.get("method", "GET") if scope["type"] == "http" else "WEBSOCKET"
        ok, status, reason = decide(scope["path"], method, user, internal)
        if ok:
            scope.setdefault("state", {})["user"] = user
            return await self.app(scope, receive, send)
        if scope["type"] == "websocket":
            msg = await receive()
            if msg.get("type") == "websocket.connect":
                await send({"type": "websocket.close", "code": 4401 if status == 401 else 4403})
            return
        body = {"resourceType": "OperationOutcome",
                "issue": [{"severity": "error", "code": "login" if status == 401 else "forbidden", "diagnostics": reason}]}
        await JSONResponse(body, status_code=status)(scope, receive, send)


class LoginThrottle:
    """At most 5 failed sign-ins per username per 5 minutes (in memory)."""

    def __init__(self, limit: int = 5, window: float = 300.0):
        self.limit, self.window, self.failures = limit, window, {}

    def blocked(self, username: str) -> bool:
        now = time.time()
        recent = [t for t in self.failures.get(username, []) if now - t < self.window]
        self.failures[username] = recent
        return len(recent) >= self.limit

    def fail(self, username: str) -> None:
        self.failures.setdefault(username, []).append(time.time())

    def clear(self, username: str) -> None:
        self.failures.pop(username, None)


# ------------------------------------------------------------------ account provisioning (CLI)
def _username(name: str, taken: set[str]) -> str:
    parts = [re.sub(r"[^a-z]", "", p.lower()) for p in re.sub(r"\d+", "", name).split()]
    parts = [p for p in parts if p]
    base = ".".join([parts[0], parts[-1]]) if len(parts) >= 2 else (parts[0] if parts else "patient")
    u, i = base, 2
    while u in taken:
        u, i = f"{base}{i}", i + 1
    return u


async def provision(db_path: str, fhir_base: str, out: Path, reset: bool = False) -> list[dict]:
    from .fhir import FhirClient
    from .patients import list_patients

    init(db_path)
    existing = json.loads(out.read_text()) if out.exists() and not reset else {"accounts": []}
    known = {a["username"]: a for a in existing.get("accounts", [])}
    fhir = FhirClient(fhir_base, 60.0)
    patients = await list_patients(fhir)
    wanted = [{"username": "doctor", "role": "doctor", "displayName": "Demo clinician", "patientId": None}]
    taken = {"doctor"}
    for p in sorted(patients, key=lambda p: p["id"]):
        prior = next((a for a in known.values() if a.get("patientId") == p["id"]), None)
        u = prior["username"] if prior else _username(p.get("name") or "", taken)
        taken.add(u)
        wanted.append({"username": u, "role": "patient", "displayName": re.sub(r"\d+", "", p.get("name") or u).strip(), "patientId": p["id"]})
    accounts = []
    for a in wanted:
        prior = known.get(a["username"])
        if prior and user_exists(db_path, a["username"]) and not reset:
            accounts.append({**a, "password": prior["password"]})
            continue
        pw = secrets.token_urlsafe(9)
        upsert_user(db_path, a["username"], a["role"], a["displayName"], pw, a["patientId"])
        accounts.append({**a, "password": pw})
    out.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        json.dump({"note": "Local demo accounts for synthetic patients. Generated randomly; keep private; not committed.",
                   "generatedAt": datetime.now(timezone.utc).isoformat(), "accounts": accounts}, f, indent=2)
    os.chmod(out, 0o600)
    return accounts


def _main() -> None:
    ap = argparse.ArgumentParser(description="Create local doctor/patient accounts with random passwords.")
    ap.add_argument("command", choices=["provision"])
    ap.add_argument("--db", default=os.environ.get("APP_SQLITE_PATH", "./data/app.db"))
    ap.add_argument("--fhir-base", default=os.environ.get("FHIR_BASE_URL", "http://localhost:8090/baseR4"))
    ap.add_argument("--out", default=None, help="credentials file (default: next to the database, mode 600)")
    ap.add_argument("--reset", action="store_true", help="generate new passwords for every account")
    a = ap.parse_args()
    out = Path(a.out) if a.out else Path(a.db).resolve().parent / "credentials.json"
    from .fhir import FhirUnavailable
    try:
        accounts = asyncio.run(provision(a.db, a.fhir_base.rstrip("/"), out, a.reset))
    except FhirUnavailable:
        raise SystemExit(f"[accounts] BLOCKED: HAPI FHIR not reachable at {a.fhir_base}; start it with scripts/dev/up.sh and seed with scripts/dev/seed.sh")
    if len(accounts) == 1:
        print("[accounts] warning: no synthetic patients found in HAPI; run scripts/dev/seed.sh, then re-run this script")
    print(f"{len(accounts)} accounts ({sum(x['role'] == 'patient' for x in accounts)} patients). Credentials: {out} (mode 600)")
    for x in accounts:
        print(f"  {x['role']:<8} {x['username']:<24} {x['password']}   {x['displayName']}")


if __name__ == "__main__":
    _main()
